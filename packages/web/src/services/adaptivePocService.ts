import { openChromeAISession } from './chromeAiService.js';
import { generateCurl, generatePython, generateTypeScript, generateGo } from '../components/Inspector/pocGenerator.js';

export type PocLanguage = 'curl' | 'python' | 'typescript' | 'go';

export interface AdaptivePocInput {
  method: string;
  url: string;
  headers?: Record<string, string>;
  body?: any;
  language: PocLanguage;
  ruleId?: string;
  message?: string;
  level?: string;
  evidence?: string;
}

export interface AdaptivePocResult {
  code: string;
  model: string;
  simulated: boolean;
  explanation?: string;
  /**
   * Why a simulated result was not generated by the model: Chrome has no Prompt API, the on-device
   * model is not downloaded yet, the session or the model failed or refused, or it ran out of time.
   */
  fallbackReason?: 'unavailable' | 'downloadable' | 'failed' | 'timeout';
}

/**
 * The code in a model's reply: the body of its first fenced block, or the whole reply when it has
 * no fence. With `partial` the reply is still being streamed, so the block may be unterminated and
 * a closing fence may be only partly written.
 */
export function codeFromReply(rawText: string, partial = false): string {
  const open = rawText.match(/```[a-zA-Z0-9_-]*[^\S\n]*\n?/);
  if (!open || open.index === undefined) {
    return partial ? rawText.trim().replace(/`{1,2}$/, '') : rawText.trim();
  }
  const body = rawText.slice(open.index + open[0].length);
  const close = body.indexOf('```');
  if (close >= 0) return body.slice(0, close).trim();
  return partial ? body.replace(/\n?`{1,2}$/, '').trimEnd() : rawText.trim();
}

/**
 * Lower-case response fragments that mark a leaked SQL error. Specific enough that a fixed
 * endpoint mentioning SQL in passing (`postgresql`, `sql_filter`) still passes. Plain text with no
 * quotes or regex metacharacters, so each is safe in every generated language and in `grep -E`.
 */
export const SQL_ERROR_SIGNATURES = [
  'syntax error',
  'sqlstate',
  'error in your sql syntax',
  'unclosed quotation mark',
  'quoted string not properly terminated',
  'sqlite_error',
  'ora-00933',
  'ora-01756',
];

export type RuleKind = 'sql' | 'xss' | 'ssrf' | 'cors' | 'other';

/**
 * Maps a finding's rule ID (e.g. `swazz/sql-error-leak`, `swazz/time-based-sqli`) to the class of
 * check the fallback script asserts. Matches whole ID segments, so `nosql-injection` is not SQL.
 */
export function ruleKind(ruleId?: string): RuleKind {
  const tokens = new Set((ruleId || '').toLowerCase().split(/[^a-z0-9]+/).filter(Boolean));
  if (tokens.has('sql') || tokens.has('sqli')) return 'sql';
  if (tokens.has('xss')) return 'xss';
  if (tokens.has('ssrf') || tokens.has('oob')) return 'ssrf';
  if (tokens.has('cors')) return 'cors';
  return 'other';
}

/**
 * Deterministic fallback generator for self-contained, automated security regression test scripts.
 * Employs defensive QA assertion patterns to test patch efficacy in CI/CD without safety refusals.
 */
export function generateAlgorithmicAdaptivePoc(input: AdaptivePocInput): AdaptivePocResult {
  const rule = (input.ruleId || 'Security Finding').trim();
  const kind = ruleKind(input.ruleId);
  const lang = input.language;
  const isObject = typeof input.body === 'object' && input.body !== null;
  const bodyFormatted = isObject ? JSON.stringify(input.body, null, 2) : input.body;

  let code = '';

  if (lang === 'python') {
    code = `#!/usr/bin/env python3
"""
Automated Security Regression Test for ${rule}
Purpose: Verify if vulnerability "${rule}" is remediated.
Expected: Target API must reject malicious inputs or maintain access boundaries.
"""

import json
import requests
import sys

TARGET_URL = ${JSON.stringify(input.url)}
HEADERS = json.loads(${JSON.stringify(JSON.stringify(input.headers || {}))})
${input.body !== undefined && input.body !== null ? `PAYLOAD = json.loads(${JSON.stringify(JSON.stringify(input.body))})\n` : ''}
def verify_security_patch():
    print(f"[*] Testing {TARGET_URL} for ${rule} remediation...")
    try:
        response = requests.request(
            method="${input.method.toUpperCase()}",
            url=TARGET_URL,
            headers=HEADERS,
            ${input.body !== undefined && input.body !== null ? (isObject ? 'json=PAYLOAD,' : 'data=PAYLOAD,') : ''}
            timeout=10
        )
    except requests.exceptions.RequestException as e:
        print(f"[!] Network error connecting to target: {e}")
        sys.exit(2)

    print(f"[*] Received HTTP Status: {response.status_code}")

    # Security Regression Assertions:
    # 1. Ensure server does not trigger 500 Unhandled Internal Server Errors
    assert response.status_code != 500, "FAILED: Server crashed with 500 Internal Error (unhandled input)"

    # 2. Check for characteristic vulnerability signatures
    body_text = response.text.lower()
    ${kind === 'sql' ? `assert not any(sig in body_text for sig in ${JSON.stringify(SQL_ERROR_SIGNATURES)}), "FAILED: SQL syntax leakage detected"` :
      kind === 'xss' ? 'assert "<script" not in body_text, "FAILED: Unencoded script tag reflected in response"' :
      kind === 'ssrf' ? 'assert response.status_code in [400, 403, 422], f"FAILED: Unfiltered outbound request accepted: {response.status_code}"' :
      kind === 'cors' ? 'assert response.headers.get("access-control-allow-origin") != "*", "FAILED: Wildcard CORS origin exposed on private endpoint"' :
      'assert response.status_code in [200, 400, 401, 403, 404, 422], f"Unexpected response code: {response.status_code}"'}

    print("[+] Regression Verification PASSED: Patch is intact.")
    return True

if __name__ == "__main__":
    verify_security_patch()
`;
  } else if (lang === 'typescript') {
    code = `/**
 * Automated Security Regression Verification Test
 * Finding: ${rule}
 * Target: ${input.method.toUpperCase()} ${input.url}
 */

async function verifySecurityPatch(): Promise<boolean> {
  const url = ${JSON.stringify(input.url)};
  const headers = ${JSON.stringify(input.headers || {}, null, 2)};
  ${input.body !== undefined && input.body !== null ? `const payload = ${JSON.stringify(input.body, null, 2)};\n` : ''}
  console.log(\`[*] Verifying remediation for \${"${rule}"} at \${url}...\`);

  const response = await fetch(url, {
    method: "${input.method.toUpperCase()}",
    headers,
    ${input.body !== undefined && input.body !== null ? (isObject ? 'body: JSON.stringify(payload),' : 'body: payload,') : ''}
  });

  const text = await response.text();
  console.log(\`[*] HTTP Status: \${response.status}\`);

  // Assertions for patch validation
  if (response.status === 500) {
    throw new Error("FAILED: Server returned 500 internal error for fuzz input");
  }

  ${kind === 'sql' ? `if (${JSON.stringify(SQL_ERROR_SIGNATURES)}.some((sig) => text.toLowerCase().includes(sig))) throw new Error("FAILED: Database syntax error revealed in body");` :
    kind === 'cors' ? 'if (response.headers.get("access-control-allow-origin") === "*") throw new Error("FAILED: Permissive CORS wildcard detected");' :
    'console.log("[+] Response validation complete.");'}

  console.log("[+] Security Verification PASSED: Endpoint is protected.");
  return true;
}

verifySecurityPatch().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
`;
  } else if (lang === 'curl') {
    const rawCurl = generateCurl({
      method: input.method,
      url: input.url,
      headers: input.headers,
      body: input.body,
    });
    const escapedShellUrl = input.url.replace(/["$`\\]/g, '\\$&');

    code = `#!/usr/bin/env bash
# Automated Verification Script for ${rule}
# Runs request and verifies HTTP status and response guardrails

set -eo pipefail

echo "[*] Sending verification request to ${escapedShellUrl}..."
RESPONSE_FILE=$(mktemp)

STATUS_CODE=$(${rawCurl} -s -w "%{http_code}" -o "$RESPONSE_FILE")

echo "[*] HTTP Status: $STATUS_CODE"

if [ "$STATUS_CODE" -eq 500 ]; then
  echo "[!] FAILED: Server returned 500 Internal Server Error"
  cat "$RESPONSE_FILE"
  rm -f "$RESPONSE_FILE"
  exit 1
fi

${kind === 'sql' ? `if grep -qiE "${SQL_ERROR_SIGNATURES.join('|')}" "$RESPONSE_FILE"; then
  echo "[!] FAILED: SQL syntax error leaked in response"
  rm -f "$RESPONSE_FILE"
  exit 1
fi` : ''}

echo "[+] PASSED: ${rule} verification check passed."
rm -f "$RESPONSE_FILE"
`;
  } else {
    // Go
    code = `package main

import (
\t"fmt"
\t"io"
\t"net/http"
\t"os"
\t"strings"
\t"time"
)

// Security Regression Test: ${rule}
func main() {
\ttargetURL := ${JSON.stringify(input.url)}
\tfmt.Printf("[*] Testing %s for ${rule} remediation...\\n", targetURL)

\tclient := &http.Client{Timeout: 10 * time.Second}
\treq, err := http.NewRequest("${input.method.toUpperCase()}", targetURL, ${input.body !== undefined && input.body !== null ? `strings.NewReader(${JSON.stringify(String(bodyFormatted))})` : 'nil'})
\tif err != nil {
\t\tpanic(err)
\t}

${input.headers ? Object.entries(input.headers).map(([k, v]) => `\treq.Header.Set("${k}", "${v.replace(/"/g, '\\"')}")`).join('\n') : ''}

\tresp, err := client.Do(req)
\tif err != nil {
\t\tfmt.Fprintf(os.Stderr, "[!] Network error: %v\\n", err)
\t\tos.Exit(2)
\t}
\tdefer resp.Body.Close()

\tbodyBytes, _ := io.ReadAll(resp.Body)
\tbodyStr := strings.ToLower(string(bodyBytes))

\tfmt.Printf("[*] HTTP Status: %d\\n", resp.StatusCode)
\tif resp.StatusCode == 500 {
\t\tfmt.Fprintf(os.Stderr, "[!] FAILED: Server returned 500 Internal Server Error\\n")
\t\tos.Exit(1)
\t}

\t${kind === 'sql' ? `for _, sig := range []string{${SQL_ERROR_SIGNATURES.map(sig => JSON.stringify(sig)).join(', ')}} {
\t\tif strings.Contains(bodyStr, sig) {
\t\t\tfmt.Fprintf(os.Stderr, "[!] FAILED: SQL syntax error detected in body\\n")
\t\t\tos.Exit(1)
\t\t}
\t}` : ''}

\tfmt.Println("[+] PASSED: Security regression verification passed.")
}
`;
  }

  return {
    code: code.trim(),
    model: 'algorithmic-rules (local)',
    simulated: true,
    explanation: `Deterministic security verification script asserting remediation of ${rule}.`,
  };
}

export interface AdaptivePocOptions {
  /** Called with the text generated so far, each time the model streams more of it. */
  onPartial?: (text: string) => void;
  /** Aborts the generation; the result is then the template, and the caller is expected to drop it. */
  signal?: AbortSignal;
  /** Upper bound on the model's work before the template is used instead. */
  timeoutMs?: number;
}

/** On-device generation of a whole script can take a while; past this the template is used. */
export const ADAPTIVE_POC_TIMEOUT_MS = 120_000;

/**
 * Reads a Prompt API stream into one string, reporting progress. The current API streams only the
 * new text in each chunk; the origin-trial (`cumulative`) one sent the whole text so far.
 */
async function readPromptStream(stream: any, cumulative: boolean, onPartial?: (text: string) => void): Promise<string> {
  let text = '';
  const reader = stream.getReader();
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      const chunk = String(value ?? '');
      text = cumulative ? chunk : text + chunk;
      onPartial?.(text);
    }
  } finally {
    reader.releaseLock?.();
  }
  return text;
}

/**
 * Generates an adaptive, self-contained reproduction and verification test script.
 * Prioritizes Chrome Built-in Prompt API (Gemini Nano on-device) framed as defensive QA,
 * streaming the text as it is generated when the browser supports it, and falls back to
 * deterministic synthesis if the model is unavailable, refuses, fails or runs out of time.
 */
export async function generateAdaptivePoc(
  input: AdaptivePocInput,
  options: AdaptivePocOptions = {},
): Promise<AdaptivePocResult> {
  const fallback = generateAlgorithmicAdaptivePoc(input);

  const controller = new AbortController();
  const abort = () => controller.abort();
  if (options.signal?.aborted) return fallback;
  options.signal?.addEventListener('abort', abort, { once: true });
  let timedOut = false;
  const timer = setTimeout(() => {
    timedOut = true;
    controller.abort();
  }, options.timeoutMs ?? ADAPTIVE_POC_TIMEOUT_MS);
  // A Prompt API call that ignores its signal still must not hold the caller past the timeout.
  const aborted = new Promise<never>((_, reject) => {
    controller.signal.addEventListener('abort', () => reject(new Error('aborted')), { once: true });
  });
  aborted.catch(() => {});

  let session: any = null;
  try {
    const opening = openChromeAISession(`You are an elite QA and Application Security Engineer creating defensive automated regression test cases.
Given an API vulnerability finding and HTTP request details, generate a complete, standalone verification test script in ${input.language}.
CRITICAL INSTRUCTIONS:
1. Frame the script strictly as a DEFENSIVE QA verification test to verify that the security patch resolves the issue.
2. Include full request setup, expected assertions (e.g. rejecting injection or protecting boundaries), and informative pass/fail output.
3. Return ONLY valid, executable code inside a standard markdown code block. Do NOT include conversational explanations.`, controller.signal);
    // A session that create() hands over after the generation was given up is destroyed when it
    // arrives: nothing else holds it.
    opening.then(o => {
      if (controller.signal.aborted) o.session?.destroy?.();
    }, () => {});
    const opened = await Promise.race([opening, aborted]);
    if (opened.status !== 'ready') {
      return { ...fallback, fallbackReason: opened.status };
    }
    session = opened.session;

    const promptText = `Generate an automated regression verification test script in ${input.language}.
Target URL: ${input.url}
HTTP Method: ${input.method.toUpperCase()}
Finding Rule: ${input.ruleId || 'N/A'}
Message: ${input.message || 'N/A'}
Evidence: ${input.evidence || 'N/A'}
Headers: ${JSON.stringify(input.headers || {})}
Payload: ${typeof input.body === 'object' ? JSON.stringify(input.body) : String(input.body || '')}
Language: ${input.language}
`;

    const response: string = typeof session.promptStreaming === 'function'
      ? await Promise.race([
        readPromptStream(session.promptStreaming(promptText, { signal: controller.signal }), opened.legacy, options.onPartial),
        aborted,
      ])
      : await Promise.race([session.prompt(promptText, { signal: controller.signal }), aborted]);
    const extracted = codeFromReply(response);

    if (extracted && extracted.length > 20 && !extracted.toLowerCase().includes('i cannot assist')) {
      return {
        code: extracted,
        model: 'chrome-gemini-nano (on-device)',
        simulated: false,
        explanation: `Generated locally with Chrome Gemini Nano as an automated regression verification test for ${input.ruleId || 'this finding'}.`,
      };
    }
  } catch (err) {
    if (timedOut) {
      return { ...fallback, fallbackReason: 'timeout' };
    }
    if (options.signal?.aborted) {
      return fallback;
    }
    // eslint-disable-next-line no-console
    console.warn('[AdaptivePoC] Chrome AI inference failed or refused, using fallback:', err);
  } finally {
    clearTimeout(timer);
    options.signal?.removeEventListener('abort', abort);
    if (session && typeof session.destroy === 'function') {
      try {
        session.destroy();
      } catch {
        // ignore
      }
    }
  }

  return { ...fallback, fallbackReason: 'failed' };
}
